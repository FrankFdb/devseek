const SERVICE_V1 = lines([
  'class TaskService {',
  '  constructor(store) {',
  '    this.store = store;',
  '  }',
  '',
  "  add({ title, priority = 'normal' }) {",
  '    const normalizedTitle = String(title || "").trim();',
  "    if (!normalizedTitle) throw new TypeError('title is required');",
  "    if (!['low', 'normal', 'high'].includes(priority)) throw new TypeError('invalid priority');",
  '    const task = {',
  '      id: `task-${this.store.all().length + 1}`,',
  '      title: normalizedTitle,',
  '      priority,',
  "      status: 'open',",
  '    };',
  '    return this.store.save(task);',
  '  }',
  '',
  '  complete(id) {',
  '    const current = this.store.find(id);',
  "    if (!current) throw new Error(`unknown task: ${id}`);",
  "    return this.store.save({ ...current, status: 'done' });",
  '  }',
  '',
  '  list({ status } = {}) {',
  '    const tasks = this.store.all();',
  '    return status ? tasks.filter(task => task.status === status) : tasks;',
  '  }',
  '}',
  '',
  'module.exports = { TaskService };',
  '',
]);

