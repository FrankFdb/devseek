import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';

const root = path.resolve(new URL('..', import.meta.url).pathname);
const extensionRoot = path.join(root, 'packages', 'vscode-extension');
const tempDir = mkdtempSync(path.join(tmpdir(), 'devseek-tool-manifest-'));
const bundlePath = path.join(tempDir, 'coding-tool-schema.cjs');
const outPath = path.join(extensionRoot, 'media', 'webview-agent-tool-manifest.js');

try {
  const result = spawnSync('npx', [
    'esbuild',
    'packages/shared/src/coding-tool-schema.ts',
    '--bundle',
    '--platform=node',
    '--format=cjs',
    `--outfile=${bundlePath}`,
    '--external:vscode',
  ], {
    cwd: root,
    stdio: 'pipe',
    encoding: 'utf8',
  });
  if (result.status !== 0) {
    process.stderr.write(result.stdout || '');
    process.stderr.write(result.stderr || '');
    throw new Error(`coding tool schema bundle failed with status ${result.status}`);
  }

  const req = createRequire(import.meta.url);
  const schemas = req(bundlePath);
  if (typeof schemas.listCodingToolNames !== 'function') {
    throw new Error('coding tool schema bundle did not export listCodingToolNames');
  }

  const toolNames = [...new Set(schemas.listCodingToolNames(true).map(String))].sort();
  const content = [
    '// Generated by scripts/generate-webview-tool-manifest.mjs.',
    '// Source of truth: packages/shared/src/coding-tool-schema.ts',
    '(function(global) {',
    `  var toolNames = ${JSON.stringify(toolNames, null, 2).replace(/\n/g, '\n  ')};`,
    '  global.DevSeekAgentToolManifest = {',
    '    toolNames: toolNames,',
    '  };',
    "})(typeof globalThis !== 'undefined' ? globalThis : window);",
    '',
  ].join('\n');
  const existing = (() => {
    try { return readFileSync(outPath, 'utf8'); } catch { return ''; }
  })();
  if (existing !== content) writeFileSync(outPath, content, 'utf8');
} finally {
  rmSync(tempDir, { recursive: true, force: true });
}
